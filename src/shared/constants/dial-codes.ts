/*
 * Telephone calling codes, by country.
 *
 * Each row: the ISO 3166-1 code (the same codes as the country list),
 * the international calling code, the national (trunk) prefix a local
 * number is written with at home — the 0 of 050 in Israel, the 1 of
 * 1-212 in the US, none in Italy, where the 0 is part of the number —
 * and the shortest and longest national number the country issues.
 *
 * Generated once from the metadata of libphonenumber (Google's
 * numbering-plan data, via libphonenumber-js 1.x) and written down, as
 * the country names were: the platform needs a code to put in front of
 * a number and a sanity check on its length, not a 150KB parser in
 * every browser that opens the registration form. Seven territories in
 * the country list have no telephone service of their own (Antarctica,
 * Bouvet, South Georgia, Heard, Pitcairn, the French Southern Lands,
 * the US minor islands) and have no row.
 */
export interface DialPlan {
  /* ISO 3166-1 alpha-2, as in the country list. */
  country: string;
  /* The international calling code, digits only: '972'. */
  dial: string;
  /* The trunk prefix of a number written at home, '' for none. */
  trunk: string;
  minDigits: number;
  maxDigits: number;
}

